"""site/ is committed, so it can fall behind the source it was built from.

Everything under site/ is generated by build_site.sh and would normally be
ignored.  It is committed because Vercel deploys this repo by cloning it, and
that turns a build artifact into something that can go stale: edit `app.js`,
commit, push, and the page that deploys is the one built last week.  Nothing
else in the tree notices, because nothing else reads site/.

The oracle is the build.  ``--full`` runs build_site.sh into a temporary
directory and compares every byte of the result, which is the only way to catch
a `wordle.wasm` left behind by a change to the Rust.

Without it the check is the part that needs no compiler: the files build_site.sh
copies unchanged, and `app.js`, which it writes through `wording.Wording.served`
-- the same call rather than a reimplementation of it.

`index.html` is left to ``--full`` deliberately.  build_site.sh threads the
wasm-api.js script tag into it on the way past, and repeating that rule here
would be a second copy of it to keep in step, which is the class of failure this
file exists to catch.
"""

import argparse
import io
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

SITE = os.path.join(ROOT, "site")

# what build_site.sh copies through untouched: (source, where it lands)
COPIED = [
    ("web/style.css", "style.css"),
    ("web/wasm-api.js", "wasm-api.js"),
    ("web/solver-worker.js", "solver-worker.js"),
    ("web/vercel.json", "vercel.json"),
    ("data/wordles.json", "data/wordles.json"),
    ("data/solutions.json", "data/solutions.json"),
    ("data/answer_like.json", "data/answer_like.json"),
    ("data/wordlebot_weights.json", "data/wordlebot_weights.json"),
    ("data/derived/ind2word.json", "data/derived/ind2word.json"),
]

# Vercel's link to its project, which is not built and not committed
IGNORED = ".vercel"

REBUILD = "site/ is behind its source -- run ./build_site.sh and commit site/"


def read(path):
    with io.open(path, "rb") as handle:
        return handle.read()


def check_copies():
    """The files that reach site/ unchanged, against the ones they came from."""
    stale = []
    for source, name in COPIED:
        landed = os.path.join(SITE, name)
        if not os.path.isfile(landed):
            stale.append(f"{name} is missing from site/")
        elif read(os.path.join(ROOT, source)) != read(landed):
            stale.append(f"{name} differs from {source}")
    print(f"      {len(COPIED)} copied files")
    return stale


def check_rewritten():
    """app.js, through the same call build_site.sh writes it with."""
    from wording import Wording

    landed = os.path.join(SITE, "app.js")
    if not os.path.isfile(landed):
        return ["app.js is missing from site/"]

    want = Wording().served("web/app.js")
    with io.open(landed, encoding="utf-8", newline="") as handle:
        got = handle.read()
    print("      app.js, as wording.served writes it")
    return [] if got == want else ["app.js differs from web/app.js"]


def tree(root):
    """Every file under `root`, by path relative to it."""
    found = {}
    for base, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d != IGNORED]
        for name in names:
            full = os.path.join(base, name)
            found[os.path.relpath(full, root).replace(os.sep, "/")] = full
    return found


def check_rebuild():
    """Build the whole thing again, and compare what comes out."""
    if not shutil.which("sh"):
        print("      skipped: sh is not on the path")
        return []

    with tempfile.TemporaryDirectory() as work:
        fresh = os.path.join(work, "site")
        done = subprocess.run(["sh", "build_site.sh", fresh], cwd=ROOT,
                              capture_output=True, text=True)
        if done.returncode != 0:
            return [f"build_site.sh failed:\n{(done.stdout + done.stderr).strip()}"]

        built, committed = tree(fresh), tree(SITE)
        stale = [f"{name} is missing from site/" for name in sorted(built)
                 if name not in committed]
        stale += [f"{name} is in site/ but the build does not produce it"
                  for name in sorted(committed) if name not in built]
        for name in sorted(set(built) & set(committed)):
            if read(built[name]) != read(committed[name]):
                stale.append(f"{name} differs from a fresh build")
        print(f"      {len(built)} files rebuilt and compared byte for byte")
        return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--full", action="store_true",
                        help="rebuild the site and compare every byte")
    args = parser.parse_args()

    if not os.path.isdir(SITE):
        print(f"no site/ to check -- run ./build_site.sh")
        return 1

    stale = check_rebuild() if args.full else check_copies() + check_rewritten()
    if not stale:
        print("      site/ is in step with what built it")
        return 0

    for line in stale:
        print(f"      {line}")
    print(f"\n{REBUILD}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
